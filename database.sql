-- "now" can be overridden while the history simulation runs
create or replace function core.now() returns timestamptz language sql stable as
$$ select coalesce(nullif(current_setting('erp.now', true), '')::timestamptz, now()) $$;
create or replace function core.d(ts timestamptz) returns date language sql stable as
$$ select (ts at time zone 'America/Denver')::date $$;
create or replace function core.today() returns date language sql stable as
$$ select core.d(core.now()) $$;

