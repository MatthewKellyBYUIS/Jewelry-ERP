create or replace function public.bom_save(p_parent int, p_lines jsonb) returns void
language plpgsql security definer set search_path = public, core as $$
declare l jsonb; v_c int; v_q numeric;
begin
  perform core.require_staff();
  if exists (select 1 from bom where component_id = p_parent) then
    raise exception 'This item is a component of another item; nested bills of material are not supported';
  end if;
  delete from bom where parent_id = p_parent;
  for l in select * from jsonb_array_elements(coalesce(p_lines, '[]'::jsonb)) loop
    v_c := (l->>'component_id')::int; v_q := (l->>'qty')::numeric;
    if v_c = p_parent then raise exception 'An item cannot be a component of itself'; end if;
    if exists (select 1 from bom where parent_id = v_c) then raise exception 'A component cannot itself be a parent item (single-level BOMs)'; end if;
    if v_q is null or v_q <= 0 then raise exception 'Component quantities must be greater than zero'; end if;
    insert into bom(parent_id, component_id, qty) values (p_parent, v_c, v_q)
      on conflict (parent_id, component_id) do update set qty = bom.qty + excluded.qty;
  end loop;
  perform core.bump();
end $$;

create or replace function public.supplier_save(p jsonb) returns int
language plpgsql security definer set search_path = public, core as $$
declare v int := (p->>'id')::int; v_old int;
begin
  perform core.require_staff();
  if nullif(trim(coalesce(p->>'name', '')), '') is null then raise exception 'Supplier name is required'; end if;
  if v is null then
    insert into suppliers(name, contact_name, email, phone, address, lead_time_days, terms_days, notes, active)
    values (trim(p->>'name'), p->>'contact_name', p->>'email', p->>'phone', p->>'address',
            coalesce((p->>'lead_time_days')::int, 7), coalesce((p->>'terms_days')::int, 30), p->>'notes', coalesce((p->>'active')::boolean, true))
    returning id into v;
  else
    select lead_time_days into v_old from suppliers where id = v;
    update suppliers set name = trim(p->>'name'), contact_name = p->>'contact_name', email = p->>'email', phone = p->>'phone',
      address = p->>'address', lead_time_days = coalesce((p->>'lead_time_days')::int, lead_time_days),
      terms_days = coalesce((p->>'terms_days')::int, terms_days), notes = p->>'notes', active = coalesce((p->>'active')::boolean, active)
    where id = v;
    if not found then raise exception 'Supplier not found'; end if;
    -- items that used the old quoted lead time follow the new one (items given their own lead time keep it)
    update items set lead_time_days = (select lead_time_days from suppliers where id = v)
     where supplier_id = v and lead_time_days = v_old;
  end if;
  perform core.bump();
  return v;
end $$;

