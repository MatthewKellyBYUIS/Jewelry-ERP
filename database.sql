create or replace function public.portal_state() returns jsonb
language plpgsql stable security definer set search_path = public, core as $$
declare v_cust int; v_out jsonb;
begin
  perform core.require_user();
  select customer_id into v_cust from profiles where user_id = auth.uid();
  select jsonb_build_object(
    'me', (select jsonb_build_object('name', name, 'role', role, 'email', email) from profiles where user_id = auth.uid()),
    'version', (select v from app_version where id = 1),
    'today', core.today(),
    'company', (select value from settings where key = 'company_name'),
    'tax_rate_pct', core.setting_num('tax_rate_pct'),
    'locations', (select jsonb_agg(jsonb_build_object('id', id, 'name', name, 'address', address, 'kind', kind) order by id) from locations),
    'items', (select coalesce(jsonb_agg(jsonb_build_object(
        'id', i.id, 'sku', i.sku, 'name', i.name, 'category', i.category, 'price', i.price, 'description', i.description,
        'made_in_house', exists (select 1 from bom where parent_id = i.id),
        'eta', core.item_eta(i.id),
        'stock', (select jsonb_object_agg(l.id, greatest(0, coalesce(inv.qty, 0) - coalesce(
                     (select sum(sl.qty) from sales_order_lines sl join sales_orders o on o.id = sl.order_id
                       where o.status = 'Order Placed' and sl.item_id = i.id and o.location_id = l.id), 0)))
                    from locations l left join inventory inv on inv.item_id = i.id and inv.location_id = l.id))
        order by i.category, i.name), '[]') from items i where i.sellable and i.active),
    'orders', (select coalesce(jsonb_agg(to_jsonb(o) || jsonb_build_object(
          'location_name', (select name from locations where id = o.location_id),
          'lines', (select coalesce(jsonb_agg(to_jsonb(l) || jsonb_build_object('name', (select name from items where id = l.item_id)) order by l.id), '[]')
                      from sales_order_lines l where l.order_id = o.id))
        order by o.id desc), '[]') from sales_orders o where o.customer_id = v_cust and v_cust is not null)
  ) into v_out;
  return v_out;
end $$;

