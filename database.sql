create or replace function core.so_create(p_customer int, p_loc int, p_required date, p_lines jsonb, p_notes text, p_source text)
returns int language plpgsql set search_path = public, core as $$
declare v_id int; l jsonb; v_item items; v_qty numeric;
begin
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one item to the order';
  end if;
  if not exists (select 1 from locations where id = p_loc) then raise exception 'Choose a location'; end if;
  if p_customer is null or not exists (select 1 from customers where id = p_customer) then raise exception 'Choose a customer'; end if;
  insert into sales_orders(number, ts, customer_id, location_id, required_date, notes, source, created_by)
  values ('SO-' || nextval('core.seq_so'), core.now(), p_customer, p_loc, coalesce(p_required, core.today()), p_notes,
          coalesce(p_source, 'staff'), core.uname()) returning id into v_id;
  for l in select * from jsonb_array_elements(p_lines) loop
    select * into v_item from items where id = (l->>'item_id')::int;
    if not found then raise exception 'Unknown item on the order'; end if;
    v_qty := (l->>'qty')::numeric;
    if v_qty is null or v_qty <= 0 then raise exception 'Quantity for % must be greater than zero', v_item.name; end if;
    insert into sales_order_lines(order_id, item_id, qty, unit_price) values (v_id, v_item.id, v_qty, v_item.price);
  end loop;
  return v_id;
end $$;

create or replace function core.so_fulfill(p_id int) returns int language plpgsql set search_path = public, core as $$
declare o sales_orders; v_sale int; v_lines jsonb;
begin
  select * into o from sales_orders where id = p_id for update;
  if not found then raise exception 'Order not found'; end if;
  if o.status <> 'Order Placed' then raise exception '% is % and cannot be fulfilled', o.number, o.status; end if;
  select jsonb_agg(jsonb_build_object('item_id', item_id, 'qty', qty, 'unit_price', unit_price) order by id)
    into v_lines from sales_order_lines where order_id = p_id;
  v_sale := core.sale(o.location_id, o.customer_id, v_lines, 0, 'On account', 'order', p_id);
  update sales_orders set status = 'Fulfilled', fulfilled_at = core.now(), sale_id = v_sale where id = p_id;
  return v_sale;
end $$;

