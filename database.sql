        select core.d(ts) d, round(sum(amount), 2) amt
          from inventory_txns where type not in ('scrap_loss', 'transfer_in', 'transfer_out') group by 1 order by 1) t),
    'expenses', (select coalesce(jsonb_agg(to_jsonb(e) order by e.d desc, e.id desc), '[]') from expenses e)
  ) into v_out;
  return v_out;
end $$;

