-- ---------- returns & exchanges ----------
create or replace function core.process_return(p_sale int, p_lines jsonb, p_exch jsonb, p_loc int)
returns int language plpgsql set search_path = public, core as $$
declare
  s sales; sl sale_lines; l jsonb; v_id int; v_num text; v_q numeric; v_net numeric; v_n int := 0;
  v_sub numeric := 0; v_cogs numeric := 0; v_reason text; v_disp text; v_ex int; v_tax numeric; v_loc int;
  v_is_ex boolean := p_exch is not null and jsonb_typeof(p_exch) = 'array' and jsonb_array_length(p_exch) > 0;
begin
  select * into s from sales where id = p_sale;
  if not found then raise exception 'Original sale not found'; end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Select at least one item to return';
  end if;
  v_loc := coalesce(p_loc, s.location_id);
  v_num := 'RMA-' || nextval('core.seq_rma');
  insert into returns(number, ts, sale_id, kind, location_id, processed_by)
  values (v_num, core.now(), p_sale, case when v_is_ex then 'exchange' else 'return' end, v_loc, core.uname())
  returning id into v_id;
  for l in select * from jsonb_array_elements(p_lines) loop
    v_q := coalesce((l->>'qty')::numeric, 0);
    if v_q <= 0 then continue; end if;
    select * into sl from sale_lines where id = (l->>'sale_line_id')::int and sale_id = p_sale for update;
    if not found then raise exception 'Return line does not belong to this sale'; end if;
    if v_q > sl.qty - sl.returned_qty then
      raise exception 'Only % unit(s) of this line can still be returned', core.q(sl.qty - sl.returned_qty);
    end if;
    v_reason := nullif(trim(coalesce(l->>'reason', '')), '');
    if v_reason is null then raise exception 'A reason code is required for every returned item'; end if;
    v_disp := coalesce(l->>'disposition', 'restock');
    if v_disp not in ('restock', 'quality_repair', 'quality_fail') then raise exception 'Invalid disposition'; end if;
    v_net := round((sl.qty * sl.unit_price - sl.discount) * v_q / sl.qty, 2);
    if v_disp = 'restock' then
      perform core.receive_cost(sl.item_id, v_q, sl.unit_cost);
      perform core.stock_move(sl.item_id, v_loc, v_q, 'return', v_reason, v_num, 'Returned to sellable stock', sl.unit_cost);
    elsif v_disp = 'quality_repair' then
      -- failed inspection but repairable: back into inventory at the workshop, where the bench can rework it
      perform core.receive_cost(sl.item_id, v_q, sl.unit_cost);
      perform core.stock_move(sl.item_id, 1, v_q, 'return', v_reason, v_num, 'Quality failure - returned to workshop inventory for repair', sl.unit_cost);
    else
      perform core.stock_move(sl.item_id, v_loc,  v_q, 'return', v_reason, v_num, 'Received for inspection', sl.unit_cost);
      perform core.stock_move(sl.item_id, v_loc, -v_q, 'return_writeoff', v_reason, v_num, 'Failed quality inspection - written off', sl.unit_cost);
    end if;
    insert into return_lines(return_id, sale_line_id, item_id, qty, refund_amount, unit_cost, reason_code, disposition)
    values (v_id, sl.id, sl.item_id, v_q, v_net, sl.unit_cost, v_reason, v_disp);
    update sale_lines set returned_qty = returned_qty + v_q where id = sl.id;
    v_sub := v_sub + v_net; v_cogs := v_cogs + v_q * sl.unit_cost; v_n := v_n + 1;
  end loop;
  if v_n = 0 then raise exception 'Enter a return quantity for at least one item'; end if;
  v_tax := round(v_sub * s.tax_rate, 2);
  if v_is_ex then
    v_ex := core.sale(v_loc, s.customer_id, p_exch, 0, 'Exchange', 'exchange', null);
  end if;
  update returns set refund_subtotal = v_sub, refund_tax = v_tax, refund_total = v_sub + v_tax,
         cogs_reversed = round(v_cogs, 2), exchange_sale_id = v_ex where id = v_id;
  return v_id;
end $$;

