create or replace function public.ensure_profile(p_name text, p_role text, p_code text) returns jsonb
language plpgsql security definer set search_path = public, core as $$
declare v_uid uuid := auth.uid(); v_email text := lower(coalesce(auth.jwt()->>'email', '')); v_cust int; v_name text;
begin
  if v_uid is null then raise exception 'Please sign in'; end if;
  if exists (select 1 from profiles where user_id = v_uid) then return public.my_profile(); end if;
  v_name := coalesce(nullif(trim(coalesce(p_name, '')), ''), split_part(v_email, '@', 1), 'User');
  if p_role = 'staff' then
    if coalesce(p_code, '') <> (select value from settings where key = 'staff_signup_code') then
      raise exception 'That staff access code is not correct';
    end if;
    insert into profiles(user_id, email, name, role) values (v_uid, v_email, v_name, 'staff');
  else
    select id into v_cust from customers where lower(email) = v_email and user_id is null order by id limit 1;
    if v_cust is null then
      insert into customers(name, email, kind) values (v_name, v_email, 'Individual') returning id into v_cust;
    end if;
    update customers set user_id = v_uid where id = v_cust;
    insert into profiles(user_id, email, name, role, customer_id) values (v_uid, v_email, v_name, 'customer', v_cust);
  end if;
  perform core.bump();
  return public.my_profile();
end $$;

