begin
  if auth.uid() is null or not exists (select 1 from profiles where user_id = auth.uid() and role = 'staff') then
    raise exception 'Staff login required';
  end if;
end $$;

create or replace function core.q(n numeric) returns text language sql immutable as
$$ select trim_scale(n)::text $$;

-- ---------- inventory ledger: every stock change goes through here ----------
create or replace function core.stock_move(p_item int, p_loc int, p_qty numeric, p_type text,
    p_reason text, p_ref text, p_note text default null, p_unit_cost numeric default null)
returns void language plpgsql set search_path = public, core as $$
declare v_qty numeric; v_cost numeric; v_name text; v_loc text;
begin
  if p_qty = 0 then return; end if;
  select cost, name into v_cost, v_name from items where id = p_item;
  if not found then raise exception 'Unknown item'; end if;
  select name into v_loc from locations where id = p_loc;
  if not found then raise exception 'Unknown location'; end if;
  insert into inventory(item_id, location_id, qty) values (p_item, p_loc, 0) on conflict do nothing;
  update inventory set qty = qty + p_qty where item_id = p_item and location_id = p_loc returning qty into v_qty;
  if v_qty < 0 then
    raise exception 'Not enough % at % (short by %)', v_name, v_loc, core.q(-v_qty);
  end if;
  v_cost := coalesce(p_unit_cost, v_cost);
  insert into inventory_txns(ts, item_id, location_id, qty_change, unit_cost, amount, type, reason_code, ref, note, user_name)
  values (core.now(), p_item, p_loc, p_qty, v_cost, round(p_qty * v_cost, 4), p_type, p_reason, p_ref, p_note, core.uname());
end $$;

-- weighted average cost: call BEFORE adding the received quantity
create or replace function core.receive_cost(p_item int, p_qty numeric, p_unit_cost numeric)
returns void language plpgsql set search_path = public, core as $$
declare v_tot numeric; v_cost numeric;
begin
  select greatest(coalesce(sum(qty), 0), 0) into v_tot from inventory where item_id = p_item;
  select cost into v_cost from items where id = p_item;
  if v_tot + p_qty > 0 then
    update items set cost = round((v_tot * v_cost + p_qty * p_unit_cost) / (v_tot + p_qty), 4) where id = p_item;
  end if;
end $$;

create or replace function core.transfer(p_item int, p_from int, p_to int, p_qty numeric, p_note text)
returns text language plpgsql set search_path = public, core as $$
declare v_ref text;
begin
  if p_qty is null or p_qty <= 0 then raise exception 'Transfer quantity must be greater than zero'; end if;
  if p_from = p_to then raise exception 'Choose two different locations'; end if;
  v_ref := 'TR-' || nextval('core.seq_tr');
  perform core.stock_move(p_item, p_from, -p_qty, 'transfer_out', null, v_ref, p_note);
  perform core.stock_move(p_item, p_to,    p_qty, 'transfer_in',  null, v_ref, p_note);
  return v_ref;
end $$;

create or replace function core.adjust(p_item int, p_loc int, p_delta numeric, p_reason text, p_note text)
returns void language plpgsql set search_path = public, core as $$
begin
  if nullif(trim(coalesce(p_reason, '')), '') is null then raise exception 'A reason code is required for adjustments'; end if;
  if p_delta is null or p_delta = 0 then raise exception 'Adjustment quantity cannot be zero'; end if;
  perform core.stock_move(p_item, p_loc, p_delta, 'adjustment', p_reason, 'ADJ', p_note);
end $$;

-- ---------- production orders ----------
create or replace function core.prod_create(p_item int, p_loc int, p_qty numeric, p_due date, p_notes text)
returns int language plpgsql set search_path = public, core as $$
declare v_id int; v_lt int;
begin
  if p_qty is null or p_qty <= 0 then raise exception 'Quantity must be greater than zero'; end if;
  if not exists (select 1 from bom where parent_id = p_item) then
    raise exception 'This item has no bill of material, so it cannot be produced';
  end if;
  select lead_time_days into v_lt from items where id = p_item;
  insert into production_orders(number, item_id, location_id, qty_planned, due_date, notes, created_by, created_at)
  values ('WO-' || nextval('core.seq_wo'), p_item, p_loc, p_qty, coalesce(p_due, core.today() + v_lt), p_notes, core.uname(), core.now())
  returning id into v_id;
  return v_id;
end $$;

create or replace function core.prod_issue(p_id int) returns void language plpgsql set search_path = public, core as $$
declare o production_orders; c record; v_short text; v_cost numeric := 0; v_loc text;
begin
  select * into o from production_orders where id = p_id for update;
  if not found then raise exception 'Production order not found'; end if;
  if o.status <> 'Planned' then raise exception '% is already %', o.number, o.status; end if;
  select name into v_loc from locations where id = o.location_id;
  select string_agg(format('%s (need %s, have %s)', i.name, core.q(b.qty * o.qty_planned), core.q(coalesce(inv.qty, 0))), '; ')
    into v_short
    from bom b join items i on i.id = b.component_id
    left join inventory inv on inv.item_id = b.component_id and inv.location_id = o.location_id
   where b.parent_id = o.item_id and coalesce(inv.qty, 0) < b.qty * o.qty_planned;
  if v_short is not null then
    raise exception 'Cannot issue %: not enough components at %: %', o.number, v_loc, v_short;
  end if;
  for c in select b.component_id, b.qty * o.qty_planned as need, i.cost
             from bom b join items i on i.id = b.component_id where b.parent_id = o.item_id order by b.component_id loop
    perform core.stock_move(c.component_id, o.location_id, -c.need, 'production_issue', null, o.number);
    insert into production_issues(prod_id, component_id, qty, unit_cost) values (p_id, c.component_id, c.need, c.cost);
    v_cost := v_cost + c.need * c.cost;
  end loop;
  update production_orders set status = 'In Process', started_at = core.now(), qty_started = qty_planned,
         component_cost = round(v_cost, 4) where id = p_id;
end $$;

create or replace function core.prod_complete(p_id int, p_good numeric, p_scrap numeric, p_rework numeric, p_reason text)
returns void language plpgsql set search_path = public, core as $$
declare o production_orders; v_unit numeric;
begin
  select * into o from production_orders where id = p_id for update;
  if not found then raise exception 'Production order not found'; end if;
  if o.status <> 'In Process' then raise exception '% must be In Process to complete (it is %)', o.number, o.status; end if;
  p_good := coalesce(p_good, 0); p_scrap := coalesce(p_scrap, 0); p_rework := coalesce(p_rework, 0);
  if p_good < 0 or p_scrap < 0 or p_rework < 0 then raise exception 'Quantities cannot be negative'; end if;
  if p_good + p_scrap <> o.qty_started then
    raise exception 'Good (%) + scrapped (%) must equal the quantity started (%)', core.q(p_good), core.q(p_scrap), core.q(o.qty_started);
  end if;
  if p_rework > p_good then raise exception 'Reworked units cannot exceed good units'; end if;
  if (p_scrap > 0 or p_rework > 0) and nullif(trim(coalesce(p_reason, '')), '') is null then
    raise exception 'A quality reason code is required when units are scrapped or reworked';
  end if;
  if p_good > 0 then
    v_unit := round(o.component_cost / p_good, 4);       -- cost rolled up from the components actually used
    perform core.receive_cost(o.item_id, p_good, v_unit);
    perform core.stock_move(o.item_id, o.location_id, p_good, 'production_receipt', null, o.number, null, v_unit);
  else
    insert into inventory_txns(ts, item_id, location_id, qty_change, unit_cost, amount, type, reason_code, ref, note, user_name)
    values (core.now(), o.item_id, o.location_id, 0, 0, -o.component_cost, 'scrap_loss', p_reason, o.number, 'Entire order scrapped', core.uname());
  end if;
  update production_orders set status = 'Completed', finished_at = core.now(), qty_good = p_good, qty_scrapped = p_scrap,
         qty_reworked = p_rework, reason_code = nullif(trim(coalesce(p_reason, '')), ''), unit_cost = v_unit where id = p_id;
end $$;

create or replace function core.auto_build(p_item int, p_loc int, p_qty numeric)
returns int language plpgsql set search_path = public, core as $$
declare v_id int; v_q numeric := ceil(p_qty);
begin
  v_id := core.prod_create(p_item, p_loc, v_q, core.today(), 'Assemble-to-order (auto-created by a sale)');
  perform core.prod_issue(v_id);
  perform core.prod_complete(v_id, v_q, 0, 0, null);
  return v_id;
end $$;

-- ---------- sales ----------
create or replace function core.sale(p_loc int, p_customer int, p_lines jsonb, p_disc_pct numeric,
    p_payment text, p_source text, p_so int)
returns int language plpgsql set search_path = public, core as $$
declare
  v_id int; v_num text; l jsonb; v_item items; v_qty numeric; v_price numeric; v_lp numeric; v_ldisc numeric;
  v_have numeric; v_sub numeric := 0; v_disc numeric := 0; v_cogs numeric := 0; v_ext numeric;
  v_rate numeric; v_tax numeric; v_od numeric := coalesce(p_disc_pct, 0);
begin
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one item';
  end if;
  if v_od < 0 or v_od > 100 then raise exception 'Discount must be between 0 and 100 percent'; end if;
  if not exists (select 1 from locations where id = p_loc) then raise exception 'Choose a location'; end if;
  v_rate := core.setting_num('tax_rate_pct') / 100;
  v_num := 'S-' || nextval('core.seq_sale');
  insert into sales(number, ts, location_id, customer_id, payment_method, source, sales_order_id, cashier, tax_rate)
  values (v_num, core.now(), p_loc, p_customer, coalesce(p_payment, 'Card'), coalesce(p_source, 'pos'), p_so, core.uname(), v_rate)
  returning id into v_id;
  for l in select * from jsonb_array_elements(p_lines) loop
    select * into v_item from items where id = (l->>'item_id')::int;
    if not found then raise exception 'Unknown item on the sale'; end if;
    v_qty := (l->>'qty')::numeric;
    if v_qty is null or v_qty <= 0 then raise exception 'Quantity for % must be greater than zero', v_item.name; end if;
    v_price := coalesce((l->>'unit_price')::numeric, v_item.price);
    v_lp := coalesce((l->>'discount_pct')::numeric, 0);
    if v_lp < 0 or v_lp > 100 then raise exception 'Line discount must be between 0 and 100 percent'; end if;
    select coalesce(sum(qty), 0) into v_have from inventory where item_id = v_item.id and location_id = p_loc;
    if v_have < v_qty then
      if exists (select 1 from bom where parent_id = v_item.id) then
        -- selling a parent with no finished stock consumes its components (assemble-to-order)
        begin
          perform core.auto_build(v_item.id, p_loc, v_qty - v_have);
        exception when others then
          raise exception 'Not enough % in stock at this location (have %, need %). It is made to order, but its components are not all at this location - transfer finished stock in, or sell from the workshop.', v_item.name, core.q(v_have), core.q(v_qty);
        end;
        select cost into v_item.cost from items where id = v_item.id;
      else
        raise exception 'Not enough % in stock at this location (have %, need %)', v_item.name, core.q(v_have), core.q(v_qty);
      end if;
    end if;
    v_ext := round(v_qty * v_price, 2);
    v_ldisc := round(v_ext * v_lp / 100, 2);
    v_ldisc := v_ldisc + round((v_ext - v_ldisc) * v_od / 100, 2);
    insert into sale_lines(sale_id, item_id, qty, unit_price, discount, unit_cost)
    values (v_id, v_item.id, v_qty, v_price, v_ldisc, v_item.cost);
    perform core.stock_move(v_item.id, p_loc, -v_qty, 'sale', null, v_num);
    v_sub := v_sub + v_ext; v_disc := v_disc + v_ldisc; v_cogs := v_cogs + v_qty * v_item.cost;
  end loop;
  v_tax := round((v_sub - v_disc) * v_rate, 2);
  update sales set subtotal = v_sub, discount = v_disc, tax = v_tax, total = v_sub - v_disc + v_tax, cogs = round(v_cogs, 2)
   where id = v_id;
  return v_id;
end $$;

create or replace function core.sale_json(p_id int) returns jsonb language sql stable set search_path = public, core as $$
  select to_jsonb(s) || jsonb_build_object(
    'customer_name', (select name from customers where id = s.customer_id),
    'location_name', (select name from locations where id = s.location_id),
    'lines', (select coalesce(jsonb_agg(to_jsonb(l) || jsonb_build_object('name', i.name, 'sku', i.sku) order by l.id), '[]'::jsonb)
                from sale_lines l join items i on i.id = l.item_id where l.sale_id = s.id))
  from sales s where s.id = p_id
$$;

