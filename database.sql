create or replace function public.item_save(p jsonb) returns int
language plpgsql security definer set search_path = public, core as $$
declare v int := (p->>'id')::int;
begin
  perform core.require_staff();
  if nullif(trim(coalesce(p->>'name', '')), '') is null then raise exception 'Item name is required'; end if;
  if nullif(trim(coalesce(p->>'sku', '')), '') is null then raise exception 'SKU is required'; end if;
  if nullif(trim(coalesce(p->>'barcode', '')), '') is null then raise exception 'Barcode is required'; end if;
  if exists (select 1 from items where barcode = trim(p->>'barcode') and id is distinct from v) then raise exception 'Another item already uses that barcode'; end if;
  if exists (select 1 from items where sku = trim(p->>'sku') and id is distinct from v) then raise exception 'Another item already uses that SKU'; end if;
  if v is null then
    insert into items(sku, barcode, name, category, kind, sellable, uom, cost, price, reorder_point, lead_time_days,
                      supplier_id, lot_policy, lot_qty, description, active)
    values (trim(p->>'sku'), trim(p->>'barcode'), trim(p->>'name'), coalesce(nullif(p->>'category', ''), 'General'),
            coalesce(nullif(p->>'kind', ''), 'component'), coalesce((p->>'sellable')::boolean, false), coalesce(nullif(p->>'uom', ''), 'ea'),
            coalesce((p->>'cost')::numeric, 0), coalesce((p->>'price')::numeric, 0), coalesce((p->>'reorder_point')::int, 0),
            coalesce((p->>'lead_time_days')::int, 7), nullif(p->>'supplier_id', '')::int,
            coalesce(nullif(p->>'lot_policy', ''), 'L4L'), greatest(coalesce((p->>'lot_qty')::int, 1), 1), p->>'description',
            coalesce((p->>'active')::boolean, true))
    returning id into v;
    insert into inventory(item_id, location_id, qty) select v, id, 0 from locations;
  else
    update items set
      sku = trim(p->>'sku'), barcode = trim(p->>'barcode'), name = trim(p->>'name'),
      category = coalesce(nullif(p->>'category', ''), category), kind = coalesce(nullif(p->>'kind', ''), kind),
      sellable = coalesce((p->>'sellable')::boolean, sellable), uom = coalesce(nullif(p->>'uom', ''), uom),
      price = coalesce((p->>'price')::numeric, price), reorder_point = coalesce((p->>'reorder_point')::int, reorder_point),
      lead_time_days = coalesce((p->>'lead_time_days')::int, lead_time_days),
      supplier_id = case when p ? 'supplier_id' then nullif(p->>'supplier_id', '')::int else supplier_id end,
      lot_policy = coalesce(nullif(p->>'lot_policy', ''), lot_policy), lot_qty = greatest(coalesce((p->>'lot_qty')::int, lot_qty), 1),
      description = case when p ? 'description' then p->>'description' else description end,
      active = coalesce((p->>'active')::boolean, active),
      -- cost is system-maintained (weighted average); it can only be typed in while there is no stock
      cost = case when (p->>'cost') is not null and (select coalesce(sum(qty), 0) from inventory where item_id = v) = 0
                  then (p->>'cost')::numeric else cost end
    where id = v;
    if not found then raise exception 'Item not found'; end if;
  end if;
  perform core.bump();
  return v;
end $$;

