create or replace function core.po_receive(p_id int, p_lines jsonb, p_loc int, p_final boolean)
returns void language plpgsql set search_path = public, core as $$
declare po purchase_orders; pl po_lines; l jsonb; v_q numeric; v_n int := 0; v_terms int; v_done boolean; v_loc int;
begin
  select * into po from purchase_orders where id = p_id for update;
  if not found then raise exception 'Purchase order not found'; end if;
  if po.status <> 'Order Sent' then raise exception '% must be in Order Sent status to receive (it is %)', po.number, po.status; end if;
  v_loc := coalesce(p_loc, po.location_id);
  if p_lines is not null and jsonb_typeof(p_lines) = 'array' then
    for l in select * from jsonb_array_elements(p_lines) loop
      v_q := coalesce((l->>'qty')::numeric, 0);
      if v_q <= 0 then continue; end if;
      select * into pl from po_lines where id = (l->>'line_id')::int and po_id = p_id for update;
      if not found then raise exception 'Line does not belong to this purchase order'; end if;
      if v_q > pl.qty_ordered - pl.qty_received then
        raise exception 'Cannot receive % - only % still outstanding on that line', core.q(v_q), core.q(pl.qty_ordered - pl.qty_received);
      end if;
      perform core.receive_cost(pl.item_id, v_q, pl.unit_cost);
      perform core.stock_move(pl.item_id, v_loc, v_q, 'po_receipt', null, po.number, null, pl.unit_cost);
      insert into po_receipts(po_id, po_line_id, ts, qty, location_id, received_by) values (p_id, pl.id, core.now(), v_q, v_loc, core.uname());
      update po_lines set qty_received = qty_received + v_q where id = pl.id;
      v_n := v_n + 1;
    end loop;
  end if;
  if v_n = 0 and not coalesce(p_final, false) then raise exception 'Enter a received quantity for at least one line'; end if;
  select terms_days into v_terms from suppliers where id = po.supplier_id;
  v_done := not exists (select 1 from po_lines where po_id = p_id and qty_received < qty_ordered);
  update purchase_orders set
     first_receipt_date = case when v_n > 0 then coalesce(first_receipt_date, core.today()) else first_receipt_date end,
     due_date = case when v_n > 0 then coalesce(due_date, core.today() + v_terms) else due_date end,
     status = case when v_done or coalesce(p_final, false) then 'Received' else status end,
     received_date = case when v_done or coalesce(p_final, false) then core.today() else received_date end
   where id = p_id;
end $$;

