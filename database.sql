-- ---------- promise dates (when will an out-of-stock item be available?) ----------
create or replace function core.purchase_eta(p_item int) returns date language sql stable set search_path = public, core as $$
  select coalesce(
    (select min(greatest(p.expected_date, core.today())) from purchase_orders p join po_lines pl on pl.po_id = p.id
      where p.status = 'Order Sent' and pl.item_id = p_item and pl.qty_received < pl.qty_ordered),
    core.today() + (select lead_time_days from items where id = p_item))
$$;

create or replace function core.item_eta(p_item int) returns date language plpgsql stable set search_path = public, core as $$
declare v_onhand numeric; v_dem numeric; v_d date; v_lt int; v_max date;
begin
  select coalesce(sum(qty), 0) into v_onhand from inventory where item_id = p_item;
  select coalesce(sum(l.qty), 0) into v_dem from sales_order_lines l join sales_orders o on o.id = l.order_id
   where o.status = 'Order Placed' and l.item_id = p_item;
  if v_onhand - v_dem > 0 then return null; end if;          -- available now
  if not exists (select 1 from bom where parent_id = p_item) then
    return core.purchase_eta(p_item);                          -- purchased item: next PO or supplier lead time
  end if;
  select lead_time_days into v_lt from items where id = p_item;
  select min(greatest(due_date, core.today())) into v_d from production_orders
   where item_id = p_item and status in ('Planned', 'In Process');
  if v_d is not null then return v_d; end if;                  -- already being made
  select coalesce(max(core.purchase_eta(b.component_id)), core.today()) into v_max
    from bom b where b.parent_id = p_item
     and (select coalesce(sum(qty), 0) from inventory where item_id = b.component_id) < b.qty;
  return v_max + v_lt;                                         -- wait for short components, then build
end $$;
